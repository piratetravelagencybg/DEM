export type BlogImageKind = 'visualization' | 'stock'

export interface BlogImage {
  src: string
  alt: string
  kind: BlogImageKind
  caption: string
  credit?: string
  sourceUrl?: string
}

export interface BlogLink {
  label: string
  href: string
  description?: string
}

export type BlogBlock =
  | { type: 'heading'; level: 2 | 3; text: string }
  | { type: 'paragraph'; text: string }
  | { type: 'list'; style: 'bullet' | 'numbered'; items: string[] }
  | { type: 'note'; tone: 'info' | 'tip' | 'important'; title?: string; text: string }
  | ({ type: 'image' } & BlogImage)
  | { type: 'links'; title: string; links: BlogLink[] }

export interface BlogPost {
  slug: string
  title: string
  description: string
  category: string
  date: string
  dateModified?: string
  heroImage: BlogImage
  blocks: BlogBlock[]
  readingTimeMinutes: number
}

type BlogPostDraft = Omit<BlogPost, 'readingTimeMinutes'>

