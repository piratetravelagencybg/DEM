export function formatBlogDate(isoDate: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(isoDate)
  if (!match) return isoDate

  const year = Number(match[1])
  const month = Number(match[2])
  const day = Number(match[3])
  if (month < 1 || month > 12 || day < 1 || day > 31) return isoDate

  return `${day} ${MONTHS[month - 1]} ${year}`
}

function textFromBlock(block: BlogBlock): string {
  switch (block.type) {
    case 'heading':
    case 'paragraph':
      return block.text
    case 'list':
      return block.items.join(' ')
    case 'note':
      return `${block.title ?? ''} ${block.text}`
    case 'image':
      return `${block.alt} ${block.caption}`
    case 'links':
      return `${block.title} ${block.links
        .map((link) => `${link.label} ${link.description ?? ''}`)
        .join(' ')}`
  }
}

/** Returns a stable whole-minute estimate from the visible article copy. */
export function calculateReadingTime(
  blocks: readonly BlogBlock[],
  wordsPerMinute = 200,
): number {
  const safeWordsPerMinute = Number.isFinite(wordsPerMinute)
    ? Math.max(1, Math.floor(wordsPerMinute))
    : 200
  const wordCount = blocks
    .map(textFromBlock)
    .join(' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean).length

  return Math.max(1, Math.ceil(wordCount / safeWordsPerMinute))
}

const visualization = (src: string, alt: string): BlogImage => ({
  src,
  alt,
  kind: 'visualization',
  caption: 'Примерна визуализация',
})

const stock = (
  src: string,
  alt: string,
  author: string,
  platform: 'Pexels' | 'Unsplash',
  sourceUrl: string,
): BlogImage => ({
  src,
  alt,
  kind: 'stock',
  caption: `Илюстративна снимка: ${author} / ${platform}`,
  credit: `${author} / ${platform}`,
  sourceUrl,
})

const h2 = (text: string): BlogBlock => ({ type: 'heading', level: 2, text })
const h3 = (text: string): BlogBlock => ({ type: 'heading', level: 3, text })
const p = (text: string): BlogBlock => ({ type: 'paragraph', text })
const bullets = (items: string[]): BlogBlock => ({ type: 'list', style: 'bullet', items })
const numbered = (items: string[]): BlogBlock => ({ type: 'list', style: 'numbered', items })
const note = (
  text: string,
  title?: string,
  tone: 'info' | 'tip' | 'important' = 'tip',
): BlogBlock => ({ type: 'note', tone, title, text })
const image = (value: BlogImage): BlogBlock => ({ type: 'image', ...value })
const links = (title: string, items: BlogLink[]): BlogBlock => ({
  type: 'links',
  title,
  links: items,
})

